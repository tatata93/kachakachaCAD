const CommandDescriptor* FindCommand(std::string_view id)
{
    const auto& table = CommandCatalog();
    const auto found = std::find_if(table.begin(), table.end(),
        [id](const CommandDescriptor& item) { return item.id == id; });
    return found == table.end() ? nullptr : &*found;
}

