def validate(data):
    sources = {s['id'] for s in data['sources']}
    assert len(sources) == len(data['sources'])
    assert len({i['id'] for i in data['items']}) == len(data['items'])
    assert len(data['items']) >= 65
    for item in data['items']:
        assert all(item[k] for k in ('region','name','evidence','observed','current','decision','unresolved','code'))
        assert set(item['sources']) <= sources, item['id']
    for d in data['dimensions']:
        assert d['source'] is None or d['source'] in sources


