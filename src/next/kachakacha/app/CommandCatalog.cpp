std::string_view SelectionPredicateNameJa(SelectionPredicate value) noexcept
{
    switch (value) {
    case SelectionPredicate::Always: return "常に使えます。";
    case SelectionPredicate::HasDocument: return "文書がありません。";
    case SelectionPredicate::HasUndo: return "戻せる操作がありません。";
    case SelectionPredicate::HasRedo: return "やり直せる操作がありません。";
    case SelectionPredicate::HasVisibleGeometry: return "見えているものがありません。";
    case SelectionPredicate::OneWorkPlane: return "作業平面を1つ選んでください。";
    case SelectionPredicate::OnePlanarFaceOrWorkPlane: return "平らな面か作業平面を1つ選んでください。";
    case SelectionPredicate::ZeroOrOneGroup: return "グループは1つまで選べます。";
    case SelectionPredicate::OneOrMoreWires: return "ワイヤーを1つ以上選んでください。";
    case SelectionPredicate::TwoWireChains: return "鎖を2つ選んでください。";
    case SelectionPredicate::OneClosedProfile: return "閉じた輪郭を1つ選んでください。";
    case SelectionPredicate::OneOrMoreClosedProfiles: return "閉じた輪郭を1つ以上選んでください。";
    case SelectionPredicate::OnePart: return "部品を1つ選んでください。";
    case SelectionPredicate::TwoParts: return "部品を2つ選んでください。";
    case SelectionPredicate::OneDerivedEntity: return "派生したものを1つ選んでください。";
    case SelectionPredicate::OneFabricationModel: return "製作モデルを1つ選んでください。";
    case SelectionPredicate::OneFabricationPanel: return "部材を1つ選んでください。";
    case SelectionPredicate::OneOrMorePatterns: return "型紙を1つ以上選んでください。";
    case SelectionPredicate::OneOrMoreSelectedCurves: return "曲線を1つ以上選んでください。";
    case SelectionPredicate::OnePartOrSurface: return "部品か形状ガイドを1つ選んでください。";
    }
    return "";
}

